"""Embed the GLB models into models.js so the game works from file:// (no fetch needed).

Run from the repo root:  python3 tools/pack-models.py
"""
import base64, os

PACKED = ['teddy', 'duck', 'rocket', 'blocks', 'plants']  # roomba.glb is kept for the Crayon Roomba update
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines = ['// Generated by tools/pack-models.py from assets/models/*.glb. Do not edit by hand.', 'window.CRAY_MODELS = {']
for name in PACKED:
    with open(os.path.join(root, 'assets', 'models', name + '.glb'), 'rb') as f:
        lines.append(f'  {name}: "{base64.b64encode(f.read()).decode()}",')
lines.append('};')
with open(os.path.join(root, 'models.js'), 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('models.js', os.path.getsize(os.path.join(root, 'models.js')) // 1024, 'KB')
